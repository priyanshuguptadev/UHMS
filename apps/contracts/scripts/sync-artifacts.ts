import { readFileSync, writeFileSync, existsSync, mkdirSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);

const contractsDir = resolve(__dirname, "..");
const webConfigDir = resolve(contractsDir, "../web/config");
const artifactPath = resolve(contractsDir, "artifacts/contracts/UHMS.sol/UHMS.json");
const deployedContractsPath = resolve(webConfigDir, "deployedContracts.json");
const contractsTsPath = resolve(webConfigDir, "contracts.ts");

export interface DeploymentRecord {
  address: `0x${string}`;
  chainId: number;
  networkName?: string;
  deployedAt: string;
}

export function syncArtifacts(newDeployment?: {
  address: `0x${string}`;
  chainId: number;
  networkName?: string;
}) {
  if (!existsSync(artifactPath)) {
    console.error(`Artifact not found at ${artifactPath}. Run 'hardhat compile' first.`);
    return;
  }

  if (!existsSync(webConfigDir)) {
    mkdirSync(webConfigDir, { recursive: true });
  }

  // 1. Read ABI from artifact
  const artifact = JSON.parse(readFileSync(artifactPath, "utf-8"));
  const abi = artifact.abi;

  // 2. Read or initialize deployedContracts.json
  let deployments: Record<string, DeploymentRecord> = {};
  if (existsSync(deployedContractsPath)) {
    try {
      deployments = JSON.parse(readFileSync(deployedContractsPath, "utf-8"));
    } catch {
      deployments = {};
    }
  }

  // 3. If a new deployment was provided, update record
  if (newDeployment) {
    deployments[String(newDeployment.chainId)] = {
      address: newDeployment.address,
      chainId: newDeployment.chainId,
      networkName: newDeployment.networkName ?? "unknown",
      deployedAt: new Date().toISOString(),
    };

    writeFileSync(
      deployedContractsPath,
      JSON.stringify(deployments, null, 2) + "\n",
      "utf-8"
    );
    console.log(`Updated ${deployedContractsPath}`);

    const envLocalPath = resolve(webConfigDir, "../.env.local");
    if (existsSync(envLocalPath)) {
      let envContent = readFileSync(envLocalPath, "utf-8");
      if (envContent.includes("NEXT_PUBLIC_UHMS_ADDRESS=")) {
        envContent = envContent.replace(
          /NEXT_PUBLIC_UHMS_ADDRESS=.*/,
          `NEXT_PUBLIC_UHMS_ADDRESS=${newDeployment.address}`
        );
      } else {
        envContent += `\nNEXT_PUBLIC_UHMS_ADDRESS=${newDeployment.address}\n`;
      }
      writeFileSync(envLocalPath, envContent, "utf-8");
      console.log(`Updated NEXT_PUBLIC_UHMS_ADDRESS in ${envLocalPath}`);
    }
  }

  // 4. Generate contracts.ts with typed ABI (as const)
  const contractsTsContent = `// Auto-generated by scripts/sync-artifacts.ts. Do not edit manually.

export const UHMS_ABI = ${JSON.stringify(abi, null, 2)} as const;

export type UHMSAbi = typeof UHMS_ABI;

export interface DeploymentInfo {
  address: \`0x\${string}\`;
  chainId: number;
  networkName?: string;
  deployedAt: string;
}

export const DEPLOYED_CONTRACTS: Record<string, DeploymentInfo> = ${JSON.stringify(
    deployments,
    null,
    2
  )} as const;

/**
 * Returns the UHMS contract address for a given chainId.
 * Priority:
 * 1. NEXT_PUBLIC_UHMS_ADDRESS env var
 * 2. Deployed address for the specific chainId
 * 3. Fallback to the first available deployed contract address
 */
export function getUHMSAddress(chainId?: number): \`0x\${string}\` | undefined {
  if (typeof process !== "undefined" && process.env?.NEXT_PUBLIC_UHMS_ADDRESS) {
    return process.env.NEXT_PUBLIC_UHMS_ADDRESS as \`0x\${string}\`;
  }
  if (chainId && DEPLOYED_CONTRACTS[String(chainId)]) {
    return DEPLOYED_CONTRACTS[String(chainId)].address;
  }
  const first = Object.values(DEPLOYED_CONTRACTS)[0];
  return first ? first.address : undefined;
}
`;

  writeFileSync(contractsTsPath, contractsTsContent, "utf-8");
  console.log(`Generated strongly-typed ABI in ${contractsTsPath}`);
}

// When run directly as a script
if (process.argv[1] === __filename) {
  syncArtifacts();
}
